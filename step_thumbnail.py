def strongest_mid_beat(beats: list[dict]) -> dict | None:
    """A strong mid-video emotional beat: most emphasis words, longer wins."""
    mids = [b for b in beats[1:-1]
            if (float(b.get("end", 0) or 0) - float(b.get("start", 0) or 0)) >= 1.5]
    if not mids:
        mids = beats[1:-1] or beats
    if not mids:
        return None
    return max(mids, key=lambda b: (len(b.get("emphasis_words") or []),
                                    float(b.get("end", 0)) -
                                    float(b.get("start", 0))))


def find_run(output_dir: str, run_id: str | None) -> Path:
    base = Path(output_dir)
    if run_id:
        folder = base / run_id
        if not folder.is_dir():
            sys.exit(f"ERROR: run folder not found: {folder}")
        return folder
    candidates = [d for d in base.iterdir()
                  if d.is_dir() and (d / "final_short.mp4").is_file()]
    if not candidates:
        sys.exit("ERROR: no run folder with final_short.mp4 (render first)")
    return max(candidates, key=lambda d: d.stat().st_mtime)


def _variant_contexts(run_folder: Path, variant_pref: str,
                      api_key: str | None) -> dict:
    """Texts + per-variant illustration contexts from the beats JSON."""
    timings_file = run_folder / "word_timings.json"
    if not timings_file.is_file():
        raise RuntimeError("word_timings.json missing (old run?)")
    timings = json.loads(timings_file.read_text(encoding="utf-8"))
    beats = [b for b in (timings.get("beats") or [])
             if isinstance(b, dict) and b.get("text")]
    mode = "beats" if beats else "classic"

    if beats:
        hook_beat = beats[0]
        hook_text = str(hook_beat["text"]).strip()
        emphasis = list(hook_beat.get("emphasis_words") or [])
        mid_beat = strongest_mid_beat(beats)
        mid_text = str(mid_beat["text"]).strip() if mid_beat else ""
        mid_emphasis = list(mid_beat.get("emphasis_words") or []) \
            if mid_beat else []
    else:
        script = timings.get("script", "")
        sentences = [s.strip() for s in re.split(r"(?<=[.!?])\s+", script)
                     if s.strip()]
        hook_beat = {"emotion": "", "visual_concept": script[:120]}
        hook_text = sentences[0] if sentences else script[:80]
        emphasis = []
        mid_beat = None
        mid_text = sentences[len(sentences) // 2] if len(sentences) > 2 else ""
        mid_emphasis = []

    texts = resolve_thumbnail_texts(hook_text, mid_text, emphasis, api_key)

    def ctx_for(beat: dict | None, caption: str) -> dict:
        return {
            "run_id": run_folder.name,
            "caption": caption,
            "emotion": str((beat or {}).get("emotion", "") or ""),
            "visual_concept": str((beat or {}).get("visual_concept", "") or ""),
        }

    contexts = {
        "hook": ctx_for(hook_beat, texts["hook"]),
        "midpoint": ctx_for(mid_beat, texts["mid"]),
        "clean": ctx_for(mid_beat or hook_beat, ""),   # clean = no text
    }
    return {"mode": mode, "texts": texts, "contexts": contexts,
            "hook_emphasis": emphasis}


def generate_variant(run_folder: Path, name: str, ctx: dict, caption: str,
                     provider: str, api_key: str | None,
                     net_deadline: float) -> dict | None:
    """One variant -> {youtube: 1080x1920 JPG (Shorts primary),
    instagram: 1080x1920 PNG cover, youtube_wide: 1280x720 JPG (legacy)}.
    The vertical render is generated ONCE and split into the two upload
    files - one AI image, two encodes."""
    th_dir = run_folder / "thumbnails"
    work_dir = th_dir / "_work"
    info: dict = {"text_used": caption, "original_text": caption,
                  "emotion": ctx.get("emotion", ""),
                  "visual_concept": ctx.get("visual_concept", ""),
                  "frame_timestamp": None, "files": {}, "cost": "$0"}
    models_seen, any_file = [], False

    def _emit_vertical(base_png: Path) -> None:
        """Split one finished vertical render into the two upload files."""
        yt_dest = th_dir / f"{name}_youtube.jpg"       # Shorts thumbnails.set
        ig_dest = th_dir / f"{name}_instagram.png"     # Reels cover
        _png_to_jpg_bounded(base_png, yt_dest)
        ig_dest.write_bytes(base_png.read_bytes())
        info["files"]["youtube"] = str(yt_dest.relative_to(run_folder))
        info["files"]["instagram"] = str(ig_dest.relative_to(run_folder))

    for wide in (True, False):
        if wide:
            dest = th_dir / f"{name}_youtube_wide.jpg"      # legacy 16:9
        else:
            dest = work_dir / f"{name}_vertical_base.png"   # work render
        seed = seed_for(run_folder.name, name, "wide" if wide else "vertical")
        base_done = False

        if provider in ("auto", "pollinations"):
            if time.time() < net_deadline:
                prompt = build_prompt(name, caption, ctx, wide,
                                      paint_text=False)
                data, _ctype, model = pollinations_image(prompt, wide, seed)
                if data:
                    save_image(data, dest, wide)
                    if caption:
                        layout = overlay_headline(dest, caption, wide)
                        info["layout"] = (f"{len(layout['lines'])} lines @ "
                                          f"{layout['font_px']}px")
                    info["model"] = model
                    models_seen.append(f"pollinations-{model}")
                    any_file = base_done = True
            else:
                print(f"      {name}: network art budget spent -> "
                      "local poster")
        elif provider == "gemini" and api_key:
            prompt = build_prompt(name, caption, ctx, wide,
                                  paint_text=bool(caption))
            data = gemini_image(prompt, api_key)
            if data and caption:
                if not gemini_text_check(data, caption, api_key):
                    print("      gemini: baked text wrong -> re-generating "
                          "text-free + local typography")
                    data = gemini_image(
                        build_prompt(name, caption, ctx, wide,
                                     paint_text=False), api_key) or b""
            if data:
                dest.parent.mkdir(parents=True, exist_ok=True)
                base = work_dir / f"{name}_base_{'wide' if wide else 'vert'}.png"
                base.write_bytes(data)
                save_image(base.read_bytes(), dest, wide)
                if caption:
                    overlay_headline(dest, caption, wide)
                info["model"] = "gemini"
                models_seen.append("gemini")
                any_file = base_done = True

        if not base_done and provider in ("auto", "local"):
            art = local_artwork(ctx, wide, seed)
            dest.parent.mkdir(parents=True, exist_ok=True)
            if dest.suffix.lower() == ".jpg":
                art.convert("RGB").save(dest, "JPEG", quality=92,
                                        optimize=True)
            else:
                art.save(dest, "PNG")
            if caption:
                layout = overlay_headline(dest, caption, wide)
                info["layout"] = (f"{len(layout['lines'])} lines @ "
                                  f"{layout['font_px']}px")
            info["model"] = "local_artwork"
            models_seen.append("local_artwork")
            any_file = True

        # map the finished render onto the manifest's upload keys
        if base_done or (provider in ("auto", "local") and dest.is_file()):
            if wide:
                info["files"]["youtube_wide"] = \
                    str(dest.relative_to(run_folder))
            else:
                _emit_vertical(dest)

    if any_file:
        info["image_provider"] = " -> ".join(dict.fromkeys(models_seen)) \
            or "unknown"
        print(f"      variant '{name}': {info['image_provider']}"
              f"{' | ' + info.get('layout', '') if caption else ''}")
        return info
    print(f"      variant '{name}': no image could be generated - skipped")
    return None


def build_variants(run_folder: Path, variant_pref: str,
                   api_key: str | None, strict: bool) -> dict:
    global PROVIDER
    provider = PROVIDER
    if provider == "gemini" and not api_key:
        print("      THUMB_IMAGE_PROVIDER=gemini but GEMINI_API_KEY missing "
              "-> falling back to auto (free) chain")
        provider = "auto"

    parsed = _variant_contexts(run_folder, variant_pref, api_key)
    texts, contexts = parsed["texts"], parsed["contexts"]
    net_deadline = time.time() + POLLINATIONS_GLOBAL_BUDGET

    variants: dict[str, dict] = {}
    for name in ("hook", "midpoint", "clean"):
        if name == "midpoint" and not contexts["midpoint"]["caption"]:
            continue                          # no mid text -> skip midpoint
        caption = contexts[name]["caption"]
        try:
            info = generate_variant(run_folder, name, contexts[name],
                                    caption, provider, api_key, net_deadline)
        except Exception as exc:
            print(f"      variant '{name}': failed ({str(exc)[:90]})")
            info = None
        if info:
            variants[name] = info

    return {"variants": variants, "texts": texts, "mode": parsed["mode"],
            "preferred": variant_pref}


