_GEMINI_IMAGE_MODELS = ["gemini-2.5-flash-image",
                        "gemini-2.0-flash-preview-image-generation"]


def gemini_image(prompt: str, api_key: str) -> bytes | None:
    from google import genai
    from google.genai import types
    client = genai.Client(api_key=api_key,
                          http_options=types.HttpOptions(timeout=120000))
    for model in _GEMINI_IMAGE_MODELS:
        try:
            resp = client.models.generate_content(
                model=model, contents=prompt,
                config=types.GenerateContentConfig(
                    response_modalities=["IMAGE"], temperature=0.7))
            for cand in (resp.candidates or []):
                for part in (cand.content.parts or []):
                    if getattr(part, "inline_data", None) and \
                            part.inline_data.data:
                        print(f"      gemini image ok ({model})")
                        return part.inline_data.data
            raise RuntimeError("no image part in response")
        except Exception as exc:
            print(f"      gemini image: {model} failed ({str(exc)[:70]})")
    return None


def gemini_text_check(image_bytes: bytes, expected: str, api_key: str) -> bool:
    """Vision pass: does the baked-in text match the expected caption?"""
    try:
        from google import genai
        from google.genai import types
        from io import BytesIO
        from PIL import Image
        buf = BytesIO()
        Image.open(BytesIO(image_bytes)).convert("RGB").save(buf, "PNG")
        client = genai.Client(api_key=api_key,
                              http_options=types.HttpOptions(timeout=60000))
        resp = client.models.generate_content(
            model=GEMINI_MODELS[0],
            contents=[types.Part.from_bytes(data=buf.getvalue(),
                                            mime_type="image/png"),
                      "Transcribe EXACTLY the text visible in this image. "
                      "Reply with the text only."],
            config=types.GenerateContentConfig(max_output_tokens=60,
                                               temperature=0))
        got = re.sub(r"[^A-Z0-9' ]", "", (resp.text or "").upper())
        want = re.sub(r"[^A-Z0-9' ]", "", expected.upper())
        return want in got
    except Exception as exc:
        print(f"      gemini vision check failed ({str(exc)[:60]})")
        return False


