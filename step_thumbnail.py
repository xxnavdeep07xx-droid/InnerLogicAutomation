def main() -> int:
    parser = argparse.ArgumentParser(
        description="Generate free thumbnail variants for the newest (or "
                    "given) run")
    parser.add_argument("--run-id", help="run folder under --output-dir")
    parser.add_argument("--output-dir", default="output")
    parser.add_argument("--video", help="explicit final_short.mp4 (run = parent)")
    parser.add_argument("--variant", choices=("hook", "midpoint", "clean"),
                        default=None,
                        help="which variant becomes the upload default "
                             "(default: THUMBNAIL_VARIANT env, else hook)")
    parser.add_argument("--auto-upload", choices=("true", "false"),
                        default=None,
                        help="false = review only, upload step will not "
                             "attach (default: AUTO_UPLOAD_THUMBNAIL env)")
    parser.add_argument("--strict", action="store_true",
                        help="exit non-zero on failure (CI default is soft)")
    parser.add_argument("--list-models", action="store_true",
                        help="print provider/model info and exit (no key)")
    args = parser.parse_args()

    load_environment(None)
    if args.list_models:
        return _list_models()
    api_key = (os.getenv("GEMINI_API_KEY", "") or "").strip() or None

    run_folder = Path(args.video).parent if args.video \
        else find_run(args.output_dir, args.run_id)
    variant_pref = (args.variant or os.getenv("THUMBNAIL_VARIANT", "")
                    or DEFAULT_VARIANT).strip().lower()
    if variant_pref not in ("hook", "midpoint", "clean"):
        variant_pref = DEFAULT_VARIANT
    auto_upload = (args.auto_upload or
                   os.getenv("AUTO_UPLOAD_THUMBNAIL", "") or "true").lower() \
        not in ("0", "false", "off", "no")

    print("=" * 60)
    print("  STEP 2.6 - THUMBNAILS (free: pollinations + Anton typography)")
    print(f"  run: {run_folder.name} | provider: {PROVIDER} "
          f"| default variant: {variant_pref} | auto-attach: {auto_upload}")
    print("=" * 60)

    t0 = time.time()
    try:
        result = build_variants(run_folder, variant_pref, api_key, args.strict)
    except Exception as exc:
        print(f"WARNING: thumbnail generation failed - pipeline continues "
              f"without thumbnails ({str(exc)[:120]})")
        if args.strict:
            return 1
        return 0

    variants = result["variants"]
    if not variants:
        print("WARNING: no thumbnail variant could be generated - pipeline "
              "continues without thumbnails")
        return 1 if args.strict else 0

    # selection: preferred variant first, then hook > midpoint > clean
    order = [variant_pref] + [v for v in ("hook", "midpoint", "clean")
                              if v != variant_pref]
    chosen = next((v for v in order if variants.get(v)), None)
    selected = None
    if chosen:
        selected = {
            "variant": chosen,
            "youtube": str((run_folder / "thumbnails" / f"{chosen}_youtube.jpg")
                           .relative_to(run_folder)),
            "instagram": str((run_folder / "thumbnails" /
                              f"{chosen}_instagram.png")
                             .relative_to(run_folder)),
            "attach": auto_upload,
        }
        # tiny mobile-feed legibility proof (what it looks like scrolled past)
        try:
            from PIL import Image
            img = Image.open(run_folder / selected["instagram"])
            img.resize((270, 480), Image.LANCZOS).save(
                run_folder / "thumbnails" / "preview_mobile_selected.png")
            img_yt = Image.open(run_folder / "thumbnails" /
                                f"{chosen}_youtube.jpg")
            # the Shorts upload spec is vertical now - preview it as 9:16
            img_yt.resize((180, 320), Image.LANCZOS).save(
                run_folder / "thumbnails" / "preview_mobile_youtube.png")
        except Exception:
            pass

    manifest = {
        "run_id": run_folder.name,
        "video": "final_short.mp4",
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "mode": result["mode"],
        "generator": "pollinations + Anton typography (free, no video "
                     "frames, Shorts-first 9:16)",
        "image_provider": PROVIDER,
        "cost": "$0",
        "config": {"thumbnail_variant": variant_pref,
                   "auto_upload_thumbnail": auto_upload,
                   "image_provider": PROVIDER,
                   "pollinations_budget_s": POLLINATIONS_GLOBAL_BUDGET},
        "variants": variants,
        "selected": selected,
    }
    manifest_path = run_folder / "thumbnails" / "thumbnail_manifest.json"
    manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2),
                             encoding="utf-8")

    # review folder hygiene: drop the working candidate files
    try:
        for p in (run_folder / "thumbnails" / "_work").glob("*"):
            p.unlink()
    except Exception:
        pass

    print()
    print(f"  thumbnails ready in {time.time() - t0:.1f}s -> "
          f"{manifest_path.parent}")
    for name, info in variants.items():
        mark = " <-- default for upload" if chosen and name == chosen else ""
        print(f"    {name:9s} {info.get('image_provider', '?'):>26s} "
              f"text=\"{info.get('text_used', '')[:34]}\"{mark}")
    print("=" * 60)
    return 0


if __name__ == "__main__":
    sys.exit(main())
