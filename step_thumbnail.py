def seed_for(run_name: str, variant: str, tag: str) -> int:
    """Same run + variant + size -> same image, every time (reproducible)."""
    digest = hashlib.sha256(f"{run_name}:{variant}:{tag}".encode()).hexdigest()
    return int(digest[:8], 16)


def _accept_pollinations(content: bytes, content_type: str) -> tuple[bool, str]:
    """Acceptance gate: 200 + image/* + >20KB + PIL-verify + min side >= 500."""
    if not (content and content[:1]):
        return False, "empty body"
    if len(content) <= 20 * 1024:
        return False, f"too small ({len(content)}B)"
    if "image" not in content_type.lower():
        return False, f"content-type {content_type[:40]!r}"
    from io import BytesIO
    from PIL import Image
    try:
        probe = Image.open(BytesIO(content))
        probe.verify()
        img = Image.open(BytesIO(content))
        if min(img.size) < POLLINATIONS_MIN_SIDE:
            return False, f"resolution too low {img.size}"
    except Exception as exc:
        return False, f"corrupt image ({str(exc)[:50]})"
    return True, ""


def pollinations_image(prompt: str, wide: bool, seed: int):
    """Fetch one illustration. Returns (bytes, content_type, model) or
    (None, '', ''). Per-model time budget + jittered retries; every model in
    the chain always gets at least one attempt."""
    import requests as rq

    models = [POLLINATIONS_MODEL_ENV] if POLLINATIONS_MODEL_ENV \
        else list(POLLINATIONS_MODELS)
    req_w, req_h = (1280, 720) if wide else (1080, 1920)
    attempt = 0

    for model in models:
        model_deadline = time.time() + POLLINATIONS_MODEL_BUDGET
        while attempt < POLLINATIONS_MAX_ATTEMPTS:
            attempt += 1
            use_seed = (seed + attempt * 17) % 9_999_991   # jitter: new seed
            params = {"width": req_w, "height": req_h, "model": model,
                      "seed": use_seed, "nologo": "true", "private": "true"}
            url = POLLINATIONS_URL.format(prompt=quote(prompt, safe=""))
            try:
                resp = rq.get(url, params=params,
                              timeout=POLLINATIONS_TIMEOUT)
            except Exception as exc:
                print(f"      pollinations {model}: request error "
                      f"({str(exc)[:60]})")
                if attempt > 1 and time.time() > model_deadline:
                    break
                time.sleep(min(8, 2 + 2 * attempt))
                continue

            ok, why = _accept_pollinations(resp.content,
                                           resp.headers.get("content-type",
                                                            ""))
            if ok and resp.status_code == 200:
                print(f"      pollinations: got {len(resp.content)//1024}KB "
                      f"via {model} (seed {use_seed})")
                return resp.content, resp.headers.get("content-type", ""), model
            print(f"      pollinations {model}: try {attempt} rejected "
                  f"(HTTP {resp.status_code}, {why})")

            # 'attempt > 1' guarantees each model its FIRST try even if flux
            # burned the whole budget - turbo still gets a shot.
            if attempt > 1 and time.time() > model_deadline:
                print(f"      pollinations {model}: budget exhausted, "
                      f"handing over to the next model")
                break
            time.sleep(min(8, 2 + 2 * attempt))

    return None, "", ""


def save_image(data: bytes, dest: Path, wide: bool) -> Path:
    """Cover-crop + LANCZOS-resize to the EXACT spec (flux ignores pixels),
    then save JPG (<=2MB loop) or PNG."""
    from io import BytesIO
    from PIL import Image, ImageOps

    img = Image.open(BytesIO(data)).convert("RGB")
    target = YT_SIZE if wide else IG_SIZE
    out = ImageOps.fit(img, target, Image.LANCZOS, centering=(0.5, 0.45))

    dest.parent.mkdir(parents=True, exist_ok=True)
    if dest.suffix.lower() == ".jpg":
        quality = 92
        while quality >= 70:
            out.save(dest, "JPEG", quality=quality, optimize=True)
            if dest.stat().st_size <= 2 * 1024 * 1024:   # API limit 2 MB
                break
            quality -= 6
    else:
        out.save(dest, "PNG")
    return dest


