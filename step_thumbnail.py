def build_prompt(variant: str, caption: str, ctx: dict, wide: bool,
                 paint_text: bool = True) -> str:
    concept = str(ctx.get("visual_concept") or caption or
                  "a lone figure facing their own shadow").strip()
    emotion = str(ctx.get("emotion") or "tension").strip()

    if wide:
        aspect = ("wide 16:9 cinematic composition, main subject in the "
                  "center, generous space above")
    else:
        aspect = ("vertical 9:16 composition, main subject centered in the "
                  "middle band of the frame, calm dark negative space above "
                  "and below the subject")

    if paint_text:
        text_note = (f'Include the exact bold headline text "{caption}" at '
                     "the top, spelled EXACTLY letter for letter.")
    else:
        text_note = ("Absolutely NO text, letters, numbers, words, captions, "
                     "logos, watermarks or typography of any kind in the "
                     "image. Keep the upper-middle area as clean dark "
                     "negative space (a headline is added there later).")

    style = ("moody cinematic digital illustration, dark psychology editorial "
             "art, dramatic rim lighting, deep navy and violet palette with "
             "one small warm yellow accent light, heavy shadows, subtle film "
             "grain, high contrast, symbolic, thought-provoking, no gore")

    return (f"{concept}. Mood: {emotion}. {aspect}. Style: {style}. "
            f"{text_note}")


# ---------------------------------------------------------------------------
# Offline poster fallback (local_artwork): gradient + rim glow + grain
# ---------------------------------------------------------------------------

def _emotion_hue(ctx: dict) -> int:
    haystack = " ".join(str(ctx.get(k, "") or "")
                        for k in ("emotion", "visual_concept", "caption"))
    low = haystack.lower()
    for key, hue in GLOW_HUES.items():
        if key in low:
            return hue
    return GLOW_DEFAULT_HUE


def local_artwork(ctx: dict, wide: bool, seed: int) -> Path:
    """Never-fail offline poster: navy->violet gradient, emotion-tinted rim
    glow, film grain, vignette. NO text (the headline is overlaid after)."""
    import colorsys
    import numpy as np
    from PIL import Image, ImageDraw, ImageFilter

    w, h = YT_SIZE if wide else IG_SIZE
    rng = np.random.default_rng(seed)

    # 1. vertical navy -> violet gradient (slightly tilted per seed)
    top = np.array([11, 16, 38], dtype=np.float32)
    bot = np.array([42, 27, 74], dtype=np.float32)
    t = np.linspace(0.0, 1.0, h, dtype=np.float32)[:, None, None]
    img = top * (1 - t) + bot * t                       # (h,1,3)
    img = np.broadcast_to(img, (h, w, 3)).copy()
    tilt = int(rng.integers(0, w // 6))
    if tilt:
        shift = np.linspace(0.06, -0.06, w, dtype=np.float32)
        img += shift[None, :, None] * 60.0

    # 2. rim glow: radial ellipse of the emotion hue behind the subject area
    hue = _emotion_hue(ctx) / 360.0
    glow_rgb = np.array([int(c * 255) for c in colorsys.hsv_to_rgb(hue, 0.75,
                                                                   0.95)],
                        dtype=np.float32)
    yy, xx = np.mgrid[0:h, 0:w].astype(np.float32)
    cy, cx = h * (0.30 if not wide else 0.34), w * 0.5
    ry, rx = h * 0.34, w * 0.55
    d2 = ((yy - cy) / ry) ** 2 + ((xx - cx) / rx) ** 2
    glow = np.clip(1.0 - d2, 0.0, 1.0) ** 2.2
    img += glow[:, :, None] * glow_rgb * (0.55 + 0.1 * rng.random())

    # 3. film grain + vignette
    img += rng.normal(0.0, 9.0, img.shape).astype(np.float32)
    vign = 1.0 - 0.45 * np.clip((d2 - 0.55) / 1.2, 0.0, 1.0)
    img *= vign[:, :, None]

    frame = Image.fromarray(np.clip(img, 0, 255).astype(np.uint8))
    frame = frame.filter(ImageFilter.GaussianBlur(0.6))
    return frame


# ---------------------------------------------------------------------------
# Typography: Anton headline overlaid locally (spelling is deterministic)
# ---------------------------------------------------------------------------

def _fit_font_size(text: str, font_path: str, canvas_w: int) -> int:
    """Largest size (from FONT_SIZE_PCT_START down to FONT_SIZE_PCT_MIN of
    canvas width) that still wraps to <= MAX_LINES inside the width cap."""
    lo = int(canvas_w * FONT_SIZE_PCT_MIN)
    hi = int(canvas_w * FONT_SIZE_PCT_START)
    best = lo
    for size in range(hi, lo - 1, -2):
        stroke = max(4, size // 12)
        max_w = int(canvas_w * MAX_WIDTH_PCT)
        if len(wrap_by_width(text, font_path, size, stroke, max_w)) <= MAX_LINES:
            best = size
            break
    return max(best, lo)


def _draw_text_block(canvas, text: str, font_path: str, wide: bool) -> dict:
    """Bold title-card style headline, centered upper-middle. Returns layout
    dict with the composited RGBA layer."""
    from PIL import Image, ImageDraw, ImageFilter

    w, h = canvas.size
    size = _fit_font_size(text, font_path, w)
    if size < w * FONT_SIZE_PCT_START * 0.92:
        print(f"      text: font auto-shrunk to {size}px to stay <= "
              f"{MAX_LINES} lines")
    stroke = max(4, size // 12)
    max_w = int(w * MAX_WIDTH_PCT)
    lines = wrap_by_width(text, font_path, size, stroke, max_w)
    probe_h = int(size * 1.24)
    block_w = max_w
    block_h = probe_h * len(lines) + stroke * 2

    cx = w // 2
    cy = int(h * (TEXT_CENTER_Y_WIDE if wide else TEXT_CENTER_Y_VERTICAL))
    x0 = max(0, cx - block_w // 2)
    y0 = max(0, cy - block_h // 2)

    # soft scrim behind the text block so it reads on any artwork
    layer = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    pad = int(size * 0.55)
    scrim = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    ImageDraw.Draw(scrim).rectangle(
        [max(0, x0 - pad), max(0, y0 - pad // 2),
         min(w, x0 + block_w + pad), min(h, y0 + block_h + pad // 2)],
        fill=(0, 0, 0, SCRIM_MAX_ALPHA))
    scrim = scrim.filter(ImageFilter.GaussianBlur(size * 0.45))
    layer = Image.alpha_composite(layer, scrim)

    draw = ImageDraw.Draw(layer)
    from PIL import ImageFont
    font = ImageFont.truetype(font_path, size)
    for i, line in enumerate(lines):
        bbox = draw.textbbox((0, 0), line, font=font, stroke_width=stroke)
        lw = bbox[2] - bbox[0]
        lx = x0 + (block_w - lw) // 2 - bbox[0]
        ly = y0 + i * probe_h - bbox[1]
        # drop shadow -> stroke -> fill (same look as the v2 title card)
        draw.text((lx + max(2, size // 40), ly + max(3, size // 26)), line,
                  font=font, fill=(0, 0, 0, 150), stroke_width=stroke,
                  stroke_fill=STROKE_COLOR + (150,))
        draw.text((lx, ly), line, font=font, fill=ACCENT_YELLOW,
                  stroke_width=stroke, stroke_fill=STROKE_COLOR + (255,))

    return {"layer": layer, "lines": lines, "font_px": size,
            "block": [x0, y0, x0 + block_w, y0 + block_h]}


def _png_to_jpg_bounded(src: Path, dest: Path) -> None:
    """Re-encode a finished PNG render as JPG under the 2 MB thumbnails.set
    cap (same quality walk-down loop as save_image)."""
    from PIL import Image

    img = Image.open(src).convert("RGB")
    quality = 92
    dest.parent.mkdir(parents=True, exist_ok=True)
    while quality >= 70:
        img.save(dest, "JPEG", quality=quality, optimize=True)
        if dest.stat().st_size <= 2 * 1024 * 1024:
            break
        quality -= 6


def overlay_headline(path: Path, caption: str, wide: bool) -> dict:
    """Typeset the headline ONTO the image at `path`, in place (JPG q92 /
    PNG). Returns the layout dict for the manifest."""
    from PIL import Image

    img = Image.open(path).convert("RGBA")
    layout = _draw_text_block(img, caption, resolve_font(None), wide)
    img = Image.alpha_composite(img, layout.pop("layer"))
    if path.suffix.lower() == ".jpg":
        quality = 92
        rgb = img.convert("RGB")
        while quality >= 70:
            rgb.save(path, "JPEG", quality=quality, optimize=True)
            if path.stat().st_size <= 2 * 1024 * 1024:
                break
            quality -= 6
    else:
        img.convert("RGB").save(path, "PNG")
    return layout


