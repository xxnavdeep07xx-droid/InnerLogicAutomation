#!/usr/bin/env python3
"""
step_thumbnail.py - automatic, $0-cost thumbnail generation for every short.

Runs AFTER step2 (needs word_timings.json) and BEFORE the upload step, so the
selected thumbnail can be attached automatically:
    YouTube Shorts : 1080x1920 JPG -> thumbnails.set right after videos().insert
                     (Shorts surfaces are 9:16 - a 16:9 image gets
                     center-cropped there and loses ~68% of its width)
    Instagram      : 1080x1920 PNG -> clip_upload(thumbnail=...) cover frame
    Legacy extra   : 1280x720 JPG  -> kept for 16:9 embed/compat surfaces

Design (the FREE pipeline - no Gemini image quota, no video-frame grabs)
-----------------------------------------------------------------------
Every variant is a CREATIVE ILLUSTRATION generated by the public
Pollinations.ai Flux endpoint (no API key, no account, literally $0),
with the headline typeset LOCALLY in the bundled Anton font so spelling is
deterministic and the text stays readable at mobile-feed sizes:

    variant "hook"      = illustration for the hook beat + the hook text
    variant "midpoint"  = illustration for the strongest mid-video beat
    variant "clean"     = atmospheric illustration, no text at all

Each variant is rendered at TWO native aspect ratios (never a stretch):
    youtube     : 1080x1920 JPG (9:16 SHORTS-FIRST upload spec, <2MB loop)
    instagram   : 1080x1920 PNG (9:16 Reels cover - same vertical art + text)
    youtube_wide: 1280x720 JPG  (16:9 legacy extra, <2MB re-encode loop)
The vertical render is made ONCE and split into the YouTube JPG and the
Instagram PNG - one AI image, two encodes, zero wasted generation time.

Provider chain (THUMB_IMAGE_PROVIDER):
    auto (default) : pollinations -> local_artwork poster fallback
                     (the step is NEVER empty-handed)
    pollinations   : Pollinations only (failures skip the variant)
    local          : offline poster art only (no network)
    gemini         : LEGACY paid path (Gemini image models) - needs a key
                     and image-model quota; kept for completeness.

The Pollinations quirk: it respects aspect ratio but not exact pixels
(flux returns 1024x576 / 576x1024), so images are cover-cropped + LANCZOS
resized to the exact spec. Requests are deterministic (seed = hash of
run:variant:tag) and retried with jitter; a global time budget makes sure
the whole step can never stall the pipeline. Any failure prints a WARNING
and exits 0 (unless --strict) - a thumbnail problem can never block
publishing.

Outputs (review folder: output/<run_id>/thumbnails/)
    hook_youtube.jpg  hook_instagram.png  (+ same for midpoint/clean)
    preview_mobile_<selected>.png        (tiny legibility proof)
    thumbnail_manifest.json              (everything the upload step needs)

Config (env or CLI, all optional)
    THUMBNAIL_VARIANT        hook | midpoint | clean   (default hook)
    AUTO_UPLOAD_THUMBNAIL    true | false              (default true)
    THUMB_IMAGE_PROVIDER     auto | pollinations | local | gemini
    THUMB_IMAGE_MODEL        force one Pollinations model (default flux,turbo)
    THUMB_POLLINATIONS_BUDGET  global seconds for all network art
                             (default 420 - after that, auto falls back to
                             local posters instantly)
    GEMINI_THUMB_MODEL       text-shortening model (default flash-lite;
                             TEXT quota is free - only used to shorten hooks)
"""

